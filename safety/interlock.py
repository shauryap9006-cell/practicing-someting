def validate_prediction_through_interlock(
    features: Dict[str, Any],
    raw_p10: float,
    raw_p50: float,
    raw_p90: float,
    base_tier: str = "HIGH",
    max_speed_kmph: float = 110.0,
) -> SafetyInterlockReport:
    """Master pure-function validator. All predictions must pass before serving."""
    checks: List[CheckResult] = []
    clamp_applied = False
    tier = base_tier
    verify_required = False

    # 1. Input Sanity
    chk_input = check_input_sanity(features)
    checks.append(chk_input)
    if not chk_input.passed:
        clamp_applied = True
        tier = "LOW"
        verify_required = True

    # 2. Quantile Order & Monotonicity
    chk_q, (q10_fixed, q50_fixed, q90_fixed) = check_quantile_order(raw_p10, raw_p50, raw_p90)
    checks.append(chk_q)
    if not chk_q.passed:
        clamp_applied = True
        tier = "LOW"
        verify_required = True

    # 3. Recovery Feasibility
    curr_d = float(features.get("current_delay", 0.0))
    km_rem = float(features.get("km_remaining", 50.0))
    train_pri = int(features.get("train_priority", features.get("priority", 2)))
    chk_rec = check_recovery_feasibility(curr_d, q50_fixed, km_rem, priority=train_pri, max_speed_kmph=max_speed_kmph)
    checks.append(chk_rec)
    if not chk_rec.passed:
        clamp_applied = True
        tier = "LOW"
        verify_required = True
        if chk_rec.clamped_value is not None:
            q50_fixed = chk_rec.clamped_value
            q10_fixed = min(q10_fixed, q50_fixed)
            q90_fixed = max(q90_fixed, q50_fixed + 5.0)

    # 4. Absolute Delay Bounds
    chk_bounds, (q10_bounded, q50_bounded, q90_bounded) = check_delay_bounds(q10_fixed, q50_fixed, q90_fixed)
    checks.append(chk_bounds)
    if not chk_bounds.passed:
        clamp_applied = True
        tier = "LOW"
        verify_required = True

    # 5. Monotonic Horizon
    chk_hor = check_monotonic_horizon(curr_d, q50_bounded)
    checks.append(chk_hor)
    if not chk_hor.passed:
        clamp_applied = True
        tier = "LOW"
        verify_required = True
        if chk_hor.clamped_value is not None:
            q50_bounded = chk_hor.clamped_value

    all_passed = all(c.passed for c in checks)
    cancellation_likely = bool(curr_d > 300.0 or q50_bounded > 300.0)

    return SafetyInterlockReport(
        checks=checks,
        all_passed=all_passed,
        clamp_applied=clamp_applied,
        tier_downgrade=(tier != base_tier),
        original_p10=raw_p10,
        original_p50=raw_p50,
        original_p90=raw_p90,
        clamped_p10=q10_bounded,
        clamped_p50=q50_bounded,
        clamped_p90=q90_bounded,
        confidence_tier=tier,
        verify_with_controller=verify_required,
        human_ack_required=True,
        cancellation_likelihood=cancellation_likely,
    )


class SafetyInterlockEngine:
    """Evaluates operational actions (advisories, timetable mutations, platform allocations) against deterministic safety rules."""

    def __init__(self, db: Optional[Any] = None):
        self.db = db

    def evaluate_action(
        self,
        train_no: str,
        action_type: str,
        proposed_platform: Optional[int] = None,
        proposed_arr: Optional[str] = None,
        proposed_dep: Optional[str] = None,
    ) -> SafetyInterlockReport:
        """Evaluates operational action against safety boundaries."""
        features = {
            "current_delay": 0.0,
            "km_remaining": 50.0,
            "hops_remaining": 1,
            "train_priority": 2,
        }
        return validate_prediction_through_interlock(
            features=features,
            raw_p10=0.0,
            raw_p50=5.0,
            raw_p90=15.0,
        )
