"""RailTwin-X Safety Interlock Layer (Phase G4).

100% DETERMINISTIC SAFETY ENFORCEMENT ENGINE.
ZERO Machine Learning in the safety path.

Rules:
1. input_sanity: Feature vector completeness, finite values, physical bounds (delay >= -5, km >= 0, speed in [0, 160]).
2. recovery_feasibility: Maximum feasible delay recovery per section <= (dist / max_speed)*60 + slack.
3. quantile_order: q10 <= q50 <= q90 with non-crossing monotonic guarantees and width in [0, 180] min.
4. delay_bounds: Hard absolute limits on predictions [-5, 720] min.
5. monotonic_horizon: Maximum drift across 6h horizon <= 720 min.

Any violated rule triggers automatic clamping + confidence tier downgrade to LOW + "verify_with_controller": true.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple


@dataclass(frozen=True)
class CheckResult:
    """Individual pure-function safety check outcome."""
    name: str
    passed: bool
    code: str
    reason: str
    clamped_value: Optional[float] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "passed": self.passed,
            "code": self.code,
            "reason": self.reason,
            "clamped_value": self.clamped_value,
        }


@dataclass
class SafetyInterlockReport:
    """Immutable validation record generated by the safety interlock."""
    checks: List[CheckResult] = field(default_factory=list)
    all_passed: bool = True
    clamp_applied: bool = False
    tier_downgrade: bool = False
    original_p10: float = 0.0
    original_p50: float = 0.0
    original_p90: float = 0.0
    clamped_p10: float = 0.0
    clamped_p50: float = 0.0
    clamped_p90: float = 0.0
    confidence_tier: str = "HIGH"
    verify_with_controller: bool = False
    human_ack_required: bool = True  # Always True (Advisory only)
    cancellation_likelihood: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "all_passed": self.all_passed,
            "clamp_applied": self.clamp_applied,
            "tier_downgrade": self.tier_downgrade,
            "confidence_tier": self.confidence_tier,
            "verify_with_controller": self.verify_with_controller,
            "human_ack_required": self.human_ack_required,
            "cancellation_likelihood": self.cancellation_likelihood,
            "clamped_band": {
                "p10_min": round(self.clamped_p10, 1),
                "p50_min": round(self.clamped_p50, 1),
                "p90_min": round(self.clamped_p90, 1),
            },
            "checks": [c.to_dict() for c in self.checks],
        }


