def check_input_sanity(features: Dict[str, Any]) -> CheckResult:
    """Verifies that all required features are present, non-null, finite, and within physical domain."""
    required = ["current_delay", "km_remaining", "hops_remaining"]
    for k in required:
        if k not in features or features[k] is None:
            return CheckResult(
                name="input_sanity",
                passed=False,
                code="ERR_MISSING_FEATURE",
                reason=f"Required feature '{k}' is missing or None.",
            )

    # Check for NaN / Infinite
    for k, v in features.items():
        if isinstance(v, (int, float)):
            if math.isnan(v) or math.isinf(v):
                return CheckResult(
                    name="input_sanity",
                    passed=False,
                    code="ERR_NON_FINITE_INPUT",
                    reason=f"Feature '{k}' has non-finite value ({v}).",
                )

    c_delay = float(features["current_delay"])
    km_rem = float(features["km_remaining"])

    if c_delay < -30.0:
        return CheckResult(
            name="input_sanity",
            passed=False,
            code="ERR_DELAY_UNDERFLOW",
            reason=f"Current delay {c_delay}m is below absolute physical floor (-30m).",
            clamped_value=-5.0,
        )

    if km_rem < 0.0:
        return CheckResult(
            name="input_sanity",
            passed=False,
            code="ERR_NEGATIVE_DISTANCE",
            reason=f"Remaining distance {km_rem} km cannot be negative.",
            clamped_value=0.0,
        )

    return CheckResult(
        name="input_sanity",
        passed=True,
        code="OK_INPUT_VALID",
        reason="All features passed physical domain sanity checks.",
    )


def check_recovery_feasibility(
    current_delay: float,
    predicted_delay: float,
    distance_km: float,
    priority: int = 2,
    max_speed_kmph: float = 130.0,
    slack_min: float = 3.0,
) -> CheckResult:
    """Verifies that predicted delay recovery does not exceed maximum kinematic feasibility."""
    if current_delay <= 0 or predicted_delay >= current_delay:
        return CheckResult(
            name="recovery_feasibility",
            passed=True,
            code="OK_NO_RECOVERY_OVERREACH",
            reason="No delay reduction or train is running on-time.",
        )

    delay_reduction = current_delay - predicted_delay
    # Priority-dependent recovery rate (km per minute of recovery)
    km_per_min = 15.0 if priority == 1 else (40.0 if priority >= 4 else 20.0)
    max_feasible_recovery = (distance_km / km_per_min) + slack_min

    if delay_reduction > max_feasible_recovery:
        feasible_p50 = max(0.0, current_delay - max_feasible_recovery)
        return CheckResult(
            name="recovery_feasibility",
            passed=False,
            code="ERR_UNFEASIBLE_SPEED_RECOVERY",
            reason=(
                f"Predicted delay reduction ({delay_reduction:.1f}m over {distance_km:.1f}km) "
                f"exceeds physical track kinematic recovery limit ({max_feasible_recovery:.2f}m)."
            ),
            clamped_value=feasible_p50,
        )

    return CheckResult(
        name="recovery_feasibility",
        passed=True,
        code="OK_RECOVERY_FEASIBLE",
        reason=f"Predicted recovery ({delay_reduction:.1f}m) is kinematically plausible.",
    )


def check_quantile_order(p10: float, p50: float, p90: float) -> Tuple[CheckResult, Tuple[float, float, float]]:
    """Enforces non-crossing monotonic quantiles: p10 <= p50 <= p90, width in [0, 180] min."""
    # Check crossing
    crossed = False
    new_p10, new_p50, new_p90 = p10, p50, p90

    if new_p10 > new_p50:
        crossed = True
        new_p10 = new_p50
    if new_p50 > new_p90:
        crossed = True
        new_p90 = max(new_p50, new_p90)

    # Check width
    width = new_p90 - new_p10
    if width > 180.0:
        # Clamp width to 180m max spread
        new_p90 = new_p10 + 180.0
        return CheckResult(
            name="quantile_order",
            passed=False,
            code="ERR_EXCESSIVE_QUANTILE_WIDTH",
            reason=f"Quantile interval width ({width:.1f}m) exceeds 180m cap. Clamped.",
            clamped_value=new_p90,
        ), (new_p10, new_p50, new_p90)

    if crossed:
        return CheckResult(
            name="quantile_order",
            passed=False,
            code="ERR_QUANTILE_CROSSING",
            reason=f"Raw model quantiles crossed (q10={p10:.1f}, q50={p50:.1f}, q90={p90:.1f}). Clamped monotonically.",
            clamped_value=new_p50,
        ), (new_p10, new_p50, new_p90)

    return CheckResult(
        name="quantile_order",
        passed=True,
        code="OK_QUANTILE_MONOTONIC",
        reason="Quantiles satisfy strict monotonicity (q10 <= q50 <= q90).",
    ), (new_p10, new_p50, new_p90)


def check_quantile_order_full(
    q_vec: Union[np.ndarray, List[float]],
    tol: float = -1e-9,
) -> CheckResult:
    """Validates the ENTIRE emitted quantile vector (all 7 quantiles) for non-crossing (Bug 10).

    Zero ML dependencies, pure deterministic arithmetic check.
    """
    arr = [float(x) for x in q_vec]
    n = len(arr)
    if n < 2:
        return CheckResult(
            name="quantile_order_full",
            passed=True,
            code="OK_QUANTILE_ORDER_FULL",
            reason="Trivially monotone vector (< 2 elements).",
        )

    diffs = [arr[i + 1] - arr[i] for i in range(n - 1)]
    min_diff = min(diffs)
    if min_diff < tol:
        viol_idx = next(i for i, d in enumerate(diffs) if d < tol)
        return CheckResult(
            name="quantile_order_full",
            passed=False,
            code="ERR_QUANTILE_VECTOR_CROSSING",
            reason=f"Quantile vector crosses at index {viol_idx}->{viol_idx+1}: {arr[viol_idx]:.2f} > {arr[viol_idx+1]:.2f}.",
            clamped_value=None,
        )
    return CheckResult(
        name="quantile_order_full",
        passed=True,
        code="OK_QUANTILE_ORDER_FULL",
        reason=f"All {n} quantile levels are strictly non-crossing.",
    )


def check_delay_bounds(p10: float, p50: float, p90: float) -> Tuple[CheckResult, Tuple[float, float, float]]:
    """Enforces hard operational bounds [0.0 min, 720.0 min]."""
    clamped = False
    c_p10 = max(0.0, min(720.0, p10))
    c_p50 = max(c_p10, min(720.0, p50))
    c_p90 = max(c_p50, min(720.0, p90))

    if (c_p10 != p10) or (c_p50 != p50) or (c_p90 != p90):
        clamped = True
        return CheckResult(
            name="delay_bounds",
            passed=False,
            code="ERR_DELAY_OUT_OF_BOUNDS",
            reason=f"Prediction [{p10:.1f}, {p50:.1f}, {p90:.1f}] exceeded [0, 720] min bounds. Clamped.",
            clamped_value=c_p50,
        ), (c_p10, c_p50, c_p90)


    return CheckResult(
        name="delay_bounds",
        passed=True,
        code="OK_WITHIN_BOUNDS",
        reason="Prediction satisfies absolute delay boundaries.",
    ), (c_p10, c_p50, c_p90)


def check_monotonic_horizon(current_delay: float, predicted_delay: float, horizon_hours: float = 6.0) -> CheckResult:
    """Verifies that predicted delay change over horizon does not exceed 720 minutes drift."""
    drift = abs(predicted_delay - current_delay)
    if drift > 720.0:
        clamped = current_delay + (720.0 if predicted_delay > current_delay else -720.0)
        return CheckResult(
            name="monotonic_horizon",
            passed=False,
            code="ERR_EXCESSIVE_HORIZON_DRIFT",
            reason=f"Delay drift across horizon ({drift:.1f}m) exceeds 720m limit.",
            clamped_value=clamped,
        )

    return CheckResult(
        name="monotonic_horizon",
        passed=True,
        code="OK_HORIZON_DRIFT_VALID",
        reason=f"Horizon delay drift ({drift:.1f}m) within operational thresholds.",
    )


