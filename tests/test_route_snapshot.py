def test_app_route_table_snapshot():
    """Asserts that the application serves the exact expected list of (method, path) routes."""
    current_routes = [list(r) for r in get_app_route_table(app)]

    missing_routes = [r for r in EXPECTED_ROUTES if r not in current_routes]
    extra_routes = [r for r in current_routes if r not in EXPECTED_ROUTES]

    assert not missing_routes, f"Missing routes in app: {missing_routes}"
    assert not extra_routes, f"Unexpected extra routes in app: {extra_routes}"
    assert current_routes == EXPECTED_ROUTES
