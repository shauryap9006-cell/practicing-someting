def get_app_route_table(app) -> List[Tuple[str, str]]:
    """Recursively traverses the FastAPI route tree and returns sorted (method, path) tuples."""
    def extract_routes(routes, prefix=""):
        res = []
        for r in routes:
            if type(r).__name__ == "_IncludedRouter":
                sub_prefix = prefix + (r.include_context.prefix or "")
                res.extend(extract_routes(r.original_router.routes, sub_prefix))
            elif isinstance(r, Route):
                for m in (r.methods or set()):
                    if m != "HEAD":
                        res.append((m, prefix + r.path))
            elif isinstance(r, Mount):
                res.extend(extract_routes(r.routes or [], prefix + r.path))
        return res

    return sorted(set(extract_routes(app.routes)))


