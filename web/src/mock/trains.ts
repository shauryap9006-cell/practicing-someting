function generateJourney(trainNo: string, schedArr: string, delay: number): JourneyStop[] {
  const baseMinutes = parseInt(schedArr.split(':')[0], 10) * 60 + parseInt(schedArr.split(':')[1], 10);
  const stations = [
    { code: 'NDLS', name: 'New Delhi', km: 0, delta: -300 },
    { code: 'GZB', name: 'Ghaziabad', km: 28, delta: -260 },
    { code: 'ALJN', name: 'Aligarh Jn', km: 131, delta: -180 },
    { code: 'TDL', name: 'Tundla Jn', km: 209, delta: -120 },
    { code: 'ETW', name: 'Etawah Jn', km: 301, delta: -60 },
    { code: 'CNB', name: 'Kanpur Central', km: 440, delta: 0 },
    { code: 'FTP', name: 'Fatehpur', km: 518, delta: 55 },
    { code: 'PRYJ', name: 'Prayagraj Jn', km: 635, delta: 125 },
    { code: 'DDU', name: 'Pt. Deen Dayal Upadhyaya', km: 788, delta: 210 },
  ];

  return stations.map((s, idx) => {
    const stopMins = (baseMinutes + s.delta + 1440) % 1440;
    const h = Math.floor(stopMins / 60).toString().padStart(2, '0');
    const m = (stopMins % 60).toString().padStart(2, '0');
    const timeStr = `${h}:${m}`;
    const isPassed = s.delta < 0;
    const isCurrent = s.code === 'CNB';
    const stopDelay = isPassed ? Math.max(0, delay - (idx * 2)) : delay;

    return {
      seq: idx + 1,
      stationCode: s.code,
      stationName: s.name,
      schedArrival: timeStr,
      schedDeparture: `${h}:${((stopMins + 5) % 60).toString().padStart(2, '0')}`,
      actualArrival: isPassed ? timeStr : undefined,
      actualDeparture: isPassed ? `${h}:${((stopMins + 5) % 60).toString().padStart(2, '0')}` : undefined,
      predArrival: !isPassed ? `${Math.floor(((stopMins + stopDelay) % 1440) / 60).toString().padStart(2, '0')}:${(((stopMins + stopDelay) % 1440) % 60).toString().padStart(2, '0')}` : undefined,
      predDeparture: !isPassed ? `${Math.floor(((stopMins + stopDelay + 5) % 1440) / 60).toString().padStart(2, '0')}:${(((stopMins + stopDelay + 5) % 1440) % 60).toString().padStart(2, '0')}` : undefined,
      delayMinutes: stopDelay,
      status: isCurrent ? 'current' : isPassed ? 'passed' : 'upcoming',
      distanceKm: s.km,
    };
  });
}

