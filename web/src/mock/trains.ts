// Helper to generate delay autopsy items that sum EXACTLY to delayMinutes
function createAutopsy(totalDelay: number, trainType: string): DelayAutopsyItem[] {
  if (totalDelay === 0) {
    return [];
  }

  if (totalDelay <= 10) {
    return [
      {
        cause: 'Section Speed Restriction (PSR 45)',
        minutes: totalDelay,
        category: 'Speed Restriction',
        description: `Track maintenance caution order at Ganga Bridge section (${totalDelay}m delay added).`,
        percentage: 100,
      },
    ];
  }

  const s1 = Math.round(totalDelay * 0.45);
  const s2 = Math.round(totalDelay * 0.35);
  const s3 = totalDelay - s1 - s2; // Guarantees exact sum = totalDelay

  if (trainType === 'DFC Freight') {
    return [
      {
        cause: 'Passenger Precedence Regulation (Held at Siding)',
        minutes: s1,
        category: 'Precedence',
        description: `Held at Rooma loop siding to allow high-priority Rajdhani Express clearance.`,
        percentage: Math.round((s1 / totalDelay) * 100),
      },
      {
        cause: 'Section Congestion & Outer Signal Red',
        minutes: s2,
        category: 'Signaling',
        description: `Approaching CNB yard outer signal with heavy rake tonnage.`,
        percentage: Math.round((s2 / totalDelay) * 100),
      },
      {
        cause: 'Track Speed Caution Order',
        minutes: s3,
        category: 'Speed Restriction',
        description: `Bridge maintenance PSR 30 km/h between Unnao and Kanpur.`,
        percentage: 100 - Math.round((s1 / totalDelay) * 100) - Math.round((s2 / totalDelay) * 100),
      },
    ];
  }

  return [
    {
      cause: 'Outer Signal Approach Hold (Platform Congestion)',
      minutes: s1,
      category: 'Signaling',
      description: `Held at Kanpur Outer Home Signal waiting for preceding rake clearance on designated platform.`,
      percentage: Math.round((s1 / totalDelay) * 100),
    },
    {
      cause: 'Preceding Freight Block Precedence Gap',
      minutes: s2,
      category: 'Precedence',
      description: `Headway regulation behind slow goods train on UP Main between Bindki Road and Kanpur.`,
      percentage: Math.round((s2 / totalDelay) * 100),
    },
    {
      cause: 'Turnaround Platform Preparation Padding',
      minutes: s3,
      category: 'Turnaround',
      description: `Watering & safety inspection delay at originating terminal.`,
      percentage: 100 - Math.round((s1 / totalDelay) * 100) - Math.round((s2 / totalDelay) * 100),
    },
  ];
}

